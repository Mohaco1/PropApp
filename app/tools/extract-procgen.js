// Carries the current app's procedure generator across exactly, as source code (closures included):
//  - the answer helpers and setup-question options: engine dev/proprietor-hub.html, "RPH.qm={};" up to RPH.qm.describes,
//    plus the question-visibility rule fsFields;
//  - the procedure templates and builder: uat/layers/procedures.js, unchanged.
//  - setup-question options, wording and save rules: uat/layers/setup-questions.js, unchanged (old screens stubbed).
// Writes src/content/legacy-procgen.js. tools/check-procgen.js proves the drafts are word-for-word identical.
const fs = require('fs'); const path = require('path');
const eng = fs.readFileSync(path.resolve(__dirname, '../../dev/proprietor-hub.html'), 'utf8').split('\n');
const from = eng.findIndex(l => l.startsWith('RPH.qm={};')), to = eng.findIndex((l, i) => i > from && l.startsWith('RPH.qm.describes='));
const fsf = eng.findIndex((l, i) => i > to && l.startsWith('fsFields=function(id,a){')), fsEnd = eng.findIndex((l, i) => i > fsf && l === '};');
if (from < 0 || to < 0 || fsf < 0 || fsEnd < 0) throw Error('engine markers not found');
const qm = eng.slice(from, to + 1).join('\n'), fields = eng.slice(fsf, fsEnd + 1).join('\n');
// 2026 Regulation checklists and NSW standards added to the setup questions (engine "RPH.qm.checkItems=" up to the
// research-register block), copied unchanged.
const r26 = eng.findIndex(l => l.startsWith('RPH.qm.checkItems=')), r26End = eng.findIndex((l, i) => i > r26 && l.startsWith('// Research register:'));
if (r26 < 0 || r26End < 0) throw Error('2026 block markers not found');
const regs = eng.slice(r26, r26End).join('\n');
const proc = fs.readFileSync(path.resolve(__dirname, '../../uat/layers/procedures.js'), 'utf8');
const sqSrc = fs.readFileSync(path.resolve(__dirname, '../../uat/layers/setup-questions.js'), 'utf8');
// One wording change only: the app calls them Procedures now (N-16, P-01). The screen name in a setup note, not an obligation.
const rename = t => t.replace(/\(Policies\)/g, '(Procedures)');
const js = rename(`// GENERATED by tools/extract-procgen.js. Do not edit: re-run the tool. Source: dev/proprietor-hub.html (answer helpers)
// and uat/layers/procedures.js (procedure templates), copied unchanged so the wording stays identical.
/* eslint-disable */
export function install(env) {
  const { state, sopValues, serviceName } = env;
  const RPH = { sop: {}, rtf: {} }; RPH.hiddenOptions = new Set(['Local process reported', 'Local processes reported']);
  RPH.sop.known = v => !!v && !['Needs verification', 'Evidence pending'].includes(v);
  let fsFields, sopDocument = () => '', saved = null;
  // Stand-ins for the old screens that setup-questions.js wraps. Only the data rules are used.
  let sopSet = (n, id, values) => { saved = values; return true; }, sopSentence = () => '', fsCard = () => {}, fsServicesSelect = () => {};
  const $ = () => null, readDraft = () => null, MutationObserver = class { observe() {} };
  RPH.express = { cat: () => 'ask', ASSUME: {} }; RPH.sop.templates = {};
  RPH.step = () => {}; RPH.sv = { coreMeta: [], serviceMeta: {} };
  const serviceSourceNotes = { daa: [], delivery: [], otp: [], prescribing: [] };
  // The field lists in content/services.json already include every later insertion, so insertions run on a scratch copy.
  let sopFields = JSON.parse(JSON.stringify(env.sopFields)); const sopFieldsFor = id => sopFields[id] || [];
${qm}
${fields}
${regs}
${sqSrc}
${proc}
  sopFields = env.sopFields;
  const normalise = (ph, id, values) => { saved = null; sopSet({ serviceLead: ph.lead || '', siteScope: ph.siteScope || {} }, id, values); return saved || values; };
  return { RPH, fsFields: (id, a) => fsFields(id, a), normalise };
}
`);
fs.writeFileSync(path.resolve(__dirname, '../src/content/legacy-procgen.js'), js);
console.log('wrote legacy-procgen.js', (js.length / 1024).toFixed(0) + ' KB · engine lines', from + 1, '-', to + 1, '+', fsf + 1, '-', fsEnd + 1);
